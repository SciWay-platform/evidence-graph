"""Pure FAIR-export rendering: DataCite report, Dublin Core XML, and RO-Crate JSON-LD.

Turns a list of canonical artifact dicts (plus a collection title) into

  * a DataCite-4.7-mandatory completeness report (`fair_report`),
  * Dublin Core (OAI-DC) XML (`dublin_core_xml` / `render_dublin_core`), and
  * an RO-Crate 1.1 metadata document as JSON-LD (`ro_crate`).

`ro_crate` output validates against `evidence_graph.ro_crate_validation`.

An "artifact dict" is the canonical shape used across this library: keys `id`, `title`,
`artifact_type`, `source_system`, optional `author_or_owner` / `created_at`, and a
`structured_metadata` dict that may carry `doi`, `creators`, `publisher`, `publication_year`,
`license`, `keywords`.

Pure: no I/O, no global state. The only impurity is the publication date, which callers may pin via
`today` (defaults to today's date) so output is reproducible in tests.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date
from typing import Any

# DataCite 4.7 mandatory properties — the named profile this module reports metadata completeness against.
DATACITE_MANDATORY = ["identifier", "creators", "title", "publisher", "publicationYear", "resourceType"]

# Artifact types worth depositing in a FAIR repository. Includes the demo/connector types
# (papers + datasets/results/experiments) AND the two types produced by the bring-your-own
# ingestion paths — `document` (uploaded pdf/docx/xlsx/…) and `note` (pasted text) — so a
# user who uploads a paper and exports FAIR gets real records instead of an empty file.
DEPOSITABLE_TYPES = {"paper", "paper_summary", "result_table", "experiment", "document", "note"}


@dataclass(frozen=True)
class Producer:
    """Who produced this crate: the organisation whose export it is.

    `publisher` is a DataCite-mandatory property with real meaning in a FAIR record, so it must name
    the actual producer. The default names this library, which is at least true; an application
    embedding it should pass its own identity so downstream users can tell whose export they hold.
    """

    name: str = "evidence-graph"
    url: str = "https://github.com/SciWay-platform/evidence-graph"
    description: str = "Provenance-rich evidence export generated by the evidence-graph library."

    @property
    def crate_id(self) -> str:
        slug = re.sub(r"[^a-z0-9]+", "-", self.name.lower()).strip("-") or "producer"
        return f"#{slug}"


DEFAULT_PRODUCER = Producer()


def _today_iso(today: date | None = None) -> str:
    return (today or date.today()).isoformat()


def _meta(artifact: dict[str, Any]) -> dict[str, Any]:
    meta = artifact.get("structured_metadata") or {}
    return meta if isinstance(meta, dict) else {}


def _creators(artifact: dict[str, Any]) -> list[Any]:
    """The artifact's creators, falling back to its author_or_owner so a record is never
    creator-less when an author is known (mirrors the demo engine's behavior)."""
    meta = _meta(artifact)
    creators = meta.get("creators")
    if not creators and artifact.get("author_or_owner"):
        creators = [{"name": artifact["author_or_owner"]}]
    return creators or []


def fair_record(artifact: dict[str, Any]) -> dict[str, Any]:
    """One artifact's FAIR/DataCite completeness record."""
    meta = _meta(artifact)
    creators = meta.get("creators")
    if not creators and artifact.get("author_or_owner"):
        creators = [{"name": artifact["author_or_owner"]}]
    present = {
        "identifier": meta.get("doi"),
        "creators": creators,
        "title": artifact.get("title"),
        "publisher": meta.get("publisher"),
        "publicationYear": meta.get("publication_year"),
        "resourceType": artifact.get("artifact_type"),
    }
    missing = [f for f in DATACITE_MANDATORY if not present.get(f)]
    return {
        "id": artifact["id"],
        "title": artifact.get("title"),
        "artifact_type": artifact["artifact_type"],
        "source_system": artifact["source_system"],
        "doi": meta.get("doi"),
        "creators": creators or [],
        "publisher": meta.get("publisher"),
        "publication_year": meta.get("publication_year"),
        "license": meta.get("license"),
        "keywords": meta.get("keywords", []),
        "datacite_mandatory_present": len(DATACITE_MANDATORY) - len(missing),
        "datacite_mandatory_total": len(DATACITE_MANDATORY),
        "missing_mandatory_fields": missing,
        "fair_complete": not missing,
    }


def _depositable(artifacts: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [a for a in artifacts if a.get("artifact_type") in DEPOSITABLE_TYPES]


def fair_report(artifacts: list[dict[str, Any]]) -> dict[str, Any]:
    """DataCite-mandatory completeness report over the FAIR-depositable artifacts."""
    records = [fair_record(a) for a in _depositable(artifacts)]
    total_fields = sum(r["datacite_mandatory_total"] for r in records) or 1
    present_fields = sum(r["datacite_mandatory_present"] for r in records)
    fully = sum(1 for r in records if r["fair_complete"])
    return {
        "profile": "DataCite 4.7 mandatory properties",
        "records_total": len(records),
        "records_fully_compliant": fully,
        "metadata_completeness_pct": round(100.0 * present_fields / total_fields, 1),
        "mandatory_fields": DATACITE_MANDATORY,
        "note": "FAIR is a set of principles, not a certificate. This reports machine-readable metadata completeness against a named profile (DataCite mandatory properties) plus PID/licence presence. It is not a compliance claim.",
        "records": records,
    }


def _xml_escape(value: Any) -> str:
    text = str(value)
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )


def render_dublin_core(artifacts: list[dict[str, Any]]) -> str:
    """OAI-DC XML for the given artifacts (one <record> each)."""
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<oai_dc:dc xmlns:oai_dc="http://www.openarchives.org/OAI/2.0/oai_dc/"',
        '           xmlns:dc="http://purl.org/dc/elements/1.1/">',
    ]
    for art in artifacts:
        meta = _meta(art)
        lines.append("  <record>")
        if meta.get("doi"):
            lines.append(f"    <dc:identifier>doi:{_xml_escape(meta['doi'])}</dc:identifier>")
        lines.append(f"    <dc:identifier>sciway:{_xml_escape(art['id'])}</dc:identifier>")
        lines.append(f"    <dc:title>{_xml_escape(art.get('title', ''))}</dc:title>")
        for creator in _creators(art):
            name = creator.get("name") if isinstance(creator, dict) else creator
            orcid = creator.get("orcid") if isinstance(creator, dict) else None
            suffix = f" (ORCID:{_xml_escape(orcid)})" if orcid else ""
            lines.append(f"    <dc:creator>{_xml_escape(name)}{suffix}</dc:creator>")
        if meta.get("publisher"):
            lines.append(f"    <dc:publisher>{_xml_escape(meta['publisher'])}</dc:publisher>")
        if meta.get("publication_year") or art.get("created_at"):
            lines.append(f"    <dc:date>{_xml_escape(meta.get('publication_year') or art.get('created_at'))}</dc:date>")
        lines.append(f"    <dc:type>{_xml_escape(art['artifact_type'])}</dc:type>")
        for kw in meta.get("keywords", []):
            lines.append(f"    <dc:subject>{_xml_escape(kw)}</dc:subject>")
        if meta.get("license"):
            lines.append(f"    <dc:rights>{_xml_escape(meta['license'])}</dc:rights>")
        lines.append("  </record>")
    lines.append("</oai_dc:dc>")
    return "\n".join(lines)


def dublin_core_xml(artifacts: list[dict[str, Any]], artifact_id: str | None = None) -> str:
    """Dublin Core XML for a single artifact (when `artifact_id` is given) or all depositable ones."""
    if artifact_id:
        arts = [a for a in artifacts if a["id"] == artifact_id]
    else:
        arts = _depositable(artifacts)
    return render_dublin_core(arts)


def _crate_id(artifact: dict[str, Any]) -> str:
    return f"artifacts/{artifact['id']}"


def ro_crate(artifacts: list[dict[str, Any]], collection_title: str,
             artifact_id: str | None = None, today: date | None = None,
             history: list[dict[str, Any]] | None = None,
             producer: Producer = DEFAULT_PRODUCER) -> dict[str, Any]:
    """RO-Crate 1.1 metadata (JSON-LD) for the FAIR-depositable artifacts.

    RO-Crate packages the dataset description as linked data: a root `Dataset` entity that
    `hasPart` one data entity per artifact, each carrying provenance (source system, creator, DOI,
    license, keywords). `collection_title` names the dataset (the project / corpus). See
    https://www.researchobject.org/ro-crate/ (spec 1.1). Design intent: this describes metadata; it
    does not bundle the file payloads.

    When `history` (a project's saved Q&A) is supplied and no single `artifact_id` is requested, the
    grounded answers derived from the corpus are appended as **W3C PROV-O** nodes (answer ←
    wasDerivedFrom ← chunks ← documents, with per-node SHA-256 checksums) and linked from the root
    Dataset via `mentions` — so the research object is provenance-complete (artifacts + the reasoning
    grounded on them), not just a file listing."""
    if artifact_id:
        arts = [a for a in artifacts if a["id"] == artifact_id]
    else:
        arts = _depositable(artifacts)

    graph: list[dict[str, Any]] = [
        {
            "@type": "CreativeWork",
            "@id": "ro-crate-metadata.json",
            "conformsTo": {"@id": "https://w3id.org/ro/crate/1.1"},
            "about": {"@id": "./"},
        },
        {
            "@id": "./",
            "@type": "Dataset",
            "name": f"{collection_title} — evidence export",
            "description": (
                "Provenance-rich evidence export: FAIR-depositable artifacts (papers, results, "
                "experiments) with citation-grade metadata."
            ),
            "datePublished": _today_iso(today),
            "publisher": {"@id": producer.crate_id},
            "license": {"@id": "https://creativecommons.org/licenses/by/4.0/"},
            "hasPart": [{"@id": _crate_id(a)} for a in arts],
        },
        {
            "@id": producer.crate_id,
            "@type": "Organization",
            "name": producer.name,
            "url": producer.url,
            "description": producer.description,
        },
    ]

    seen_people: dict[str, str] = {}
    for art in arts:
        meta = _meta(art)
        author_refs = []
        for creator in _creators(art):
            name = creator.get("name") if isinstance(creator, dict) else creator
            if not name:
                continue
            pid = "#person-" + re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
            if pid not in seen_people:
                seen_people[pid] = name
                person: dict[str, Any] = {"@id": pid, "@type": "Person", "name": name}
                orcid = creator.get("orcid") if isinstance(creator, dict) else None
                if orcid:
                    person["identifier"] = f"https://orcid.org/{orcid}"
                graph.append(person)
            author_refs.append({"@id": pid})

        entity: dict[str, Any] = {
            "@id": _crate_id(art),
            "@type": "Dataset" if art["artifact_type"] in {"result_table", "experiment"} else "ScholarlyArticle",
            "name": art.get("title", art["id"]),
            "sciway:sourceSystem": art["source_system"],
            "sciway:artifactType": art["artifact_type"],
        }
        if author_refs:
            entity["author"] = author_refs
        if meta.get("doi"):
            entity["identifier"] = f"https://doi.org/{meta['doi']}"
        if meta.get("publisher"):
            entity["publisher"] = meta["publisher"]
        if meta.get("publication_year") or art.get("created_at"):
            entity["datePublished"] = str(meta.get("publication_year") or art.get("created_at"))
        if meta.get("license"):
            entity["license"] = meta["license"]
        if meta.get("keywords"):
            entity["keywords"] = meta["keywords"]
        graph.append(entity)

    context: list[Any] = [
        "https://w3id.org/ro/crate/1.1/context",
        {"sciway": "https://sciway.eu/ns#"},
    ]

    # PROV-O answer lineage (provenance-complete research object): append the derivation graph of the
    # grounded answers. Skipped for a single-artifact crate (answers span the corpus) and when there
    # is no history. Existing @ids ("artifacts/<id>") never collide with the prov ids
    # ("answer:"/"document:"/chunk ids/"sciway:activity|agent/…"), keeping the crate valid.
    if history and not artifact_id:
        from evidence_graph.provenance import answer_lineage, prov_jsonld_nodes
        crate_ids = {_crate_id(a) for a in arts}
        art_ids = {a["id"] for a in arts}
        merged: dict[str, dict[str, Any]] = {}
        answer_refs: list[dict[str, str]] = []
        for h in history:
            entries = answer_lineage(h, timestamp=str(h.get("created_at") or _today_iso(today)))
            answer = next((e for e in entries if e.entity_type == "answer"), None)
            if answer:
                answer_refs.append({"@id": answer.entity_id})
            for node in prov_jsonld_nodes(entries):
                # Tie a prov document node back to the crate's data entity when it's the same artifact.
                if node.get("sciway:entityType") == "document":
                    aid = node["@id"].split("document:", 1)[-1]
                    if aid in art_ids and f"artifacts/{aid}" in crate_ids:
                        node["prov:specializationOf"] = {"@id": f"artifacts/{aid}"}
                merged[node["@id"]] = {**merged.get(node["@id"], {}), **node}
        if answer_refs:
            graph[1]["mentions"] = answer_refs          # graph[1] is the root "./" Dataset
            graph.extend(merged.values())
            context.append({"prov": "http://www.w3.org/ns/prov#"})

    return {"@context": context, "@graph": graph}
